from __future__ import annotations

import re
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / 'public' / 'fonts' / 'figtree.woff2'
TARGET = ROOT / 'app' / 'components' / 'Wordmark.vue'

WORDS = ('himanshu', 'monochromish')
WEIGHT = 500
# how far above the baseline the page edge cuts, in x-heights
CROP = 0.13


def num(v: float) -> str:
    s = f'{v:.1f}'.rstrip('0').rstrip('.')
    return '0' if s == '-0' else s


def kern_lookups(font: TTFont) -> list:
    gpos = font['GPOS'].table
    indices: set[int] = set()
    for rec in gpos.ScriptList.ScriptRecord:
        if rec.ScriptTag not in ('latn', 'DFLT') or not rec.Script.DefaultLangSys:
            continue
        for fi in rec.Script.DefaultLangSys.FeatureIndex:
            feature = gpos.FeatureList.FeatureRecord[fi]
            if feature.FeatureTag == 'kern':
                indices.update(feature.Feature.LookupListIndex)
    return [gpos.LookupList.Lookup[i] for i in sorted(indices)]


def pair_value(lookups: list, left: str, right: str) -> int:
    total = 0
    for lookup in lookups:
        subtables = [st.ExtSubTable if lookup.LookupType == 9 else st for st in lookup.SubTable]
        for st in subtables:
            if getattr(st, 'Coverage', None) is None or left not in st.Coverage.glyphs:
                continue
            record = None
            if st.Format == 1:
                pairs = st.PairSet[st.Coverage.glyphs.index(left)].PairValueRecord
                match = next((p for p in pairs if p.SecondGlyph == right), None)
                if match is None:
                    continue
                record = match.Value1
            else:
                c1 = st.ClassDef1.classDefs.get(left, 0)
                c2 = st.ClassDef2.classDefs.get(right, 0)
                record = st.Class1Record[c1].Class2Record[c2].Value1
            if record is not None:
                total += getattr(record, 'XAdvance', 0) or 0
                total += getattr(record, 'XPlacement', 0) or 0
            break
    return total


def outline(font: TTFont, word: str) -> tuple[list[float], str, list[int]]:
    cmap = font.getBestCmap()
    glyphset = font.getGlyphSet()
    hmtx = font['hmtx']
    lookups = kern_lookups(font)
    names = [cmap[ord(ch)] for ch in word]

    svg = SVGPathPen(glyphset, ntos=num)
    bounds = BoundsPen(glyphset)
    x = 0
    kerns = []
    for i, name in enumerate(names):
        if i:
            k = pair_value(lookups, names[i - 1], name)
            kerns.append(k)
            x += k
        # flip y about the baseline
        glyphset[name].draw(TransformPen(svg, (1, 0, 0, -1, x, 0)))
        glyphset[name].draw(TransformPen(bounds, (1, 0, 0, -1, x, 0)))
        x += hmtx[name][0]

    left, top, right, _ = bounds.bounds
    crop = -CROP * font['OS/2'].sxHeight
    return [left, top, right - left, crop - top], svg.getCommands(), kerns


def main() -> None:
    font = instancer.instantiateVariableFont(TTFont(FONT), {'wght': WEIGHT})
    crop = CROP * font['OS/2'].sxHeight
    words = {word: outline(font, word) for word in WORDS}

    kerning = ', '.join(f'{word} {f"kerning {k}" if any(k) else "no kerning"}' for word, (_, _, k) in words.items())
    block = '\n'.join([
        '// wordmark.py:begin (generated by scripts/wordmark.py, do not edit by hand)',
        f'// Figtree at wght {WEIGHT}, {kerning}, cut {num(crop)} units above the baseline ({round(CROP * 100)}% of the x-height)',
        '// Each box is the ink in font units, y down; its bottom edge is the cut',
        'const WORDMARKS = {',
        *(f"  {word}: {{ ink: {{ x: {num(ink[0])}, y: {num(ink[1])}, width: {num(ink[2])}, height: {num(ink[3])} }}, path: '{d}' }}," for word, (ink, d, _) in words.items()),
        '}',
        '// wordmark.py:end',
    ])

    source = TARGET.read_text(encoding='utf-8')
    pattern = re.compile(r'// wordmark\.py:begin.*?// wordmark\.py:end', re.S)
    if not pattern.search(source):
        sys.exit(f'{TARGET} has no wordmark.py:begin/end block to replace')
    TARGET.write_text(pattern.sub(lambda _: block, source, count=1), encoding='utf-8', newline='\n')

    for word, (ink, d, kerns) in words.items():
        print(f'{word}: kerning {kerns}; ink {" ".join(num(v) for v in ink)} units; path {len(d)} chars')
    print(f'-> {TARGET.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
